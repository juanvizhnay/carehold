#!/usr/bin/env python3
"""Generate Sources/CareHold/Generated/AppConfig.swift from .env (both git-ignored).

.env format (see .env.example):
  SUPABASE_URL=https://<project>.supabase.co
  SUPABASE_PUBLISHABLE_KEY=sb_publishable_...

Refuses secret keys: only the public publishable key may ship inside the app.
"""

import base64
import ipaddress
import json
import sys
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
ENV = ROOT / ".env"
OUTPUT = ROOT / "Sources" / "CareHold" / "Generated" / "AppConfig.swift"


def fail(message: str) -> None:
    print(f"config-gen: {message}", file=sys.stderr)
    sys.exit(1)


def read_env() -> dict[str, str]:
    if not ENV.exists():
        fail(f"missing {ENV.relative_to(ROOT)} (copy .env.example)")
    values = {}
    for line in ENV.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if not sep:
            fail(f"invalid line in .env: {line!r}")
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def jwt_role(token: str) -> str | None:
    parts = token.split(".")
    if len(parts) != 3:
        return None
    payload = parts[1] + "=" * (-len(parts[1]) % 4)
    try:
        return json.loads(base64.urlsafe_b64decode(payload)).get("role")
    except (ValueError, json.JSONDecodeError):
        return None


def is_local(host: str) -> bool:
    try:
        return ipaddress.ip_address(host).is_private or ipaddress.ip_address(host).is_loopback
    except ValueError:
        return host == "localhost"


def main() -> None:
    env = read_env()
    url = env.get("SUPABASE_URL", "")
    key = env.get("SUPABASE_PUBLISHABLE_KEY", "")

    parsed = urlparse(url)
    if not parsed.netloc or parsed.scheme not in ("https", "http"):
        fail("SUPABASE_URL must be a URL")
    if parsed.scheme == "http" and not is_local(parsed.hostname or ""):
        fail("SUPABASE_URL must be https (http is only allowed for a local Supabase)")
    if key.startswith("sb_secret_") or jwt_role(key) == "service_role":
        fail("SUPABASE_PUBLISHABLE_KEY is a SECRET key. Never put it in the app; use the publishable key.")
    if not (key.startswith("sb_publishable_") or jwt_role(key) == "anon"):
        fail("SUPABASE_PUBLISHABLE_KEY must be a publishable key (sb_publishable_...)")

    swift = f"""// Generated by scripts/config-gen.py from .env. Do not edit. Do not commit.

import Data
import Foundation

enum AppConfig {{
    static let backend = BackendConfig(
        url: URL(string: {json.dumps(url)})!,
        publishableKey: {json.dumps(key)}
    )
}}
"""
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(swift, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
