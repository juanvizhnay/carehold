"""Generate supabase/seed.sql (git-ignored): two demo accounts plus a realistic care plan.

Reads from .env:
  DEMO_CLINICIAN_EMAIL / DEMO_CLINICIAN_PASSWORD   the therapist who signs in
  DEMO_PATIENT_EMAIL / DEMO_PATIENT_PASSWORD       the patient who signs in
  DEMO_TIMEZONE                                    optional, defaults to this machine's zone

Every date is relative to the day the seed runs, so the demo always looks current.
Two extra patients (who cannot sign in) fill the therapist's schedule.

Local:   scripts/seed-gen.py && npx supabase db reset
Remote:  scripts/seed-gen.py && npx supabase db push --include-seed
"""

